//! Stub implementation of the games module when the `games` Cargo feature is disabled.
//! This completely avoids compiling ~4MB of games code and native C/C++ dependencies
//! (leveldb-sys, snappy, unrar_sys, argus-udfread, hadris-iso).

macro_rules! stub_cmd {
    ($($name:ident),* $(,)?) => {
        $(
            #[tauri::command]
            pub async fn $name() -> Result<serde_json::Value, String> {
                Err("Games feature is disabled in this build".to_string())
            }
        )*
    };
}

