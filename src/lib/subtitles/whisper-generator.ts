/**
 * Whisper Subtitle Generator & Pipeline Fallback Engine
 *
 * Transcribes audio streams on-the-fly and generates valid, synchronized WebVTT/SRT
 * subtitle tracks when online subtitle providers return zero matches.
 */

import type { SubCue } from "./parser";
import { convertWhisperSegmentsToCues, type SpeechTranscriptionSegment } from "./neural-whisper-copilot";

export interface GeneratedSubtitleResult {
  vttContent: string;
  blobUrl: string;
  cueCount: number;
  durationSec: number;
  language: string;
}

/**
 * Generates clean, compliant WebVTT text from raw speech transcription segments.
 */
export function generateVttFromSpeechSegments(
  segments: SpeechTranscriptionSegment[],
  language = "en",
): string {
  const cues: SubCue[] = convertWhisperSegmentsToCues(segments);
  let vtt = `WEBVTT - Generated by Argus Whisper Copilot (${language})\n\n`;

  for (let i = 0; i < cues.length; i++) {
    const cue = cues[i];
    const startStr = formatVttTime(cue.start);
    const endStr = formatVttTime(cue.end);

    vtt += `${i + 1}\n`;
    vtt += `${startStr} --> ${endStr}\n`;
    vtt += `${cue.text}\n\n`;
  }

  return vtt;
}

function formatVttTime(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  const ms = Math.floor((seconds % 1) * 1000);

  const hh = String(h).padStart(2, "0");
  const mm = String(m).padStart(2, "0");
  const ss = String(s).padStart(2, "0");
  const mmm = String(ms).padStart(3, "0");

  return `${hh}:${mm}:${ss}.${mmm}`;
}

/**
 * Creates a mountable Blob URL for the generated WebVTT track.
 */
export function createGeneratedSubtitleBlobUrl(vttContent: string): string {
  if (typeof Blob === "undefined" || typeof URL === "undefined" || !URL.createObjectURL) {
    return "data:text/vtt;charset=utf-8," + encodeURIComponent(vttContent);
  }

  const blob = new Blob([vttContent], { type: "text/vtt;charset=utf-8" });
  return URL.createObjectURL(blob);
}
